// ✅ Safe language detection (no automatic browser detectors)
function getInitialLanguage(): 'fr' | 'en' {
  try {
    // 1. Check localStorage first
    const stored = localStorage.getItem('academy_of_pi_language');
    if (stored === 'fr' || stored === 'en') {
      return stored;
    }
    
    // 2. Try navigator.language with safety guards
    if (typeof navigator !== 'undefined' && navigator.language) {
      const browserLang = navigator.language.toLowerCase();
      if (browserLang.startsWith('fr')) return 'fr';
      if (browserLang.startsWith('en')) return 'en';
    }
  } catch (error) {
    console.warn('Language detection failed, using French:', error);
  }
  
  // 3. Default to French
  return 'fr';
}

